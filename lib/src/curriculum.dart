List<Lesson> _recognitionSequence({
  required String idPrefix,
  required String firstLessonId,
  required List<String> targets,
  required String locale,
  required String challenge,
  required String objectivePrefix,
}) {
  String idAt(int index) => index == 0
      ? firstLessonId
      : '$idPrefix-${(index + 1).toString().padLeft(3, '0')}';

  return [
    for (var i = 0; i < targets.length; i++)
      Lesson(
        id: idAt(i),
        title: challenge,
        subtitle: challenge,
        kind: LessonKind.alphabet,
        symbol: '?',
        speech: targets[i],
        locale: locale,
        challenge: challenge,
        options: [
          targets[i],
          targets[(i + 1) % targets.length],
          targets[(i + 2) % targets.length],
